/**
 * Regenerate constants/worldMap.ts — dotted-map land grid (precomputed getMapJSON).
 *
 *   node scripts/generateDottedWorldMap.mjs
 *   npm run generate:world-map
 *
 * Dev dep: dotted-map (full package — country polygons only at build time).
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { getMapJSON } from "dotted-map";
import DottedMap from "dotted-map/without-countries";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, "..", "constants", "worldMap.ts");

/** Grid rows — keep in sync with GLOBAL_ROOM_LAND_DOT_RADIUS (reference: fine diagonal grid). */
const MAP_HEIGHT = 60;
const GRID = "diagonal";

/** Trim polar/ocean padding; keep all inhabited continents (incl. NZ, Alaska, Tierra del Fuego). */
const REGION = {
  lat: { min: -55, max: 72 },
  lng: { min: -168, max: 168 },
};

const mapJsonString = getMapJSON({
  height: MAP_HEIGHT,
  grid: GRID,
  region: REGION,
});
const mapData = JSON.parse(mapJsonString);
const map = new DottedMap({ map: mapData });

const landDots = [];
for (const { x, y } of Object.values(mapData.points)) {
  landDots.push(x, y);
}

const { width, height, region, projection } = mapData;
const latMin = region.lat.min;
const latMax = region.lat.max;
const lngMin = region.lng.min;
const lngMax = region.lng.max;

const header = `/**
 * Dotted world map for the Global Room — land grid only, no borders or labels.
 *
 * GENERATED by \`node scripts/generateDottedWorldMap.mjs\` — do not edit by hand.
 *
 * Source: dotted-map (\`getMapJSON\`, grid: ${GRID}, height: ${MAP_HEIGHT}, projection: ${projection?.name ?? "mercator"}, region lat ${latMin}…${latMax} lng ${lngMin}…${lngMax}).
 * Land dots are precomputed; the app never runs geographic point-in-polygon at runtime.
 *
 * Coordinate space: map units in the SVG viewBox (0 … ${width}, 0 … ${height}).
 * Use \`projectToWorldMap\` in lib/worldMapProjection.ts to place presence dots on this canvas.
 */

export const WORLD_MAP_LAT_MAX = ${latMax};
export const WORLD_MAP_LAT_MIN = ${latMin};
export const WORLD_MAP_LNG_MAX = ${lngMax};
export const WORLD_MAP_LNG_MIN = ${lngMin};
export const WORLD_MAP_WIDTH = ${width};
export const WORLD_MAP_HEIGHT = ${height};

/** dotted-map Mercator bounds (meters) — must match the generator. */
export const WORLD_MAP_MERCATOR_X_MIN = ${mapData.X_MIN};
export const WORLD_MAP_MERCATOR_Y_MAX = ${mapData.Y_MAX};
export const WORLD_MAP_MERCATOR_X_RANGE = ${mapData.X_RANGE};
export const WORLD_MAP_MERCATOR_Y_RANGE = ${mapData.Y_RANGE};

/** Land dots: flat [x0, y0, x1, y1, …] in viewBox coordinates (${landDots.length / 2} points). */
export const WORLD_MAP_LAND_DOTS: readonly number[] = [
`;

const CHUNK = 40;
const lines = [];
for (let i = 0; i < landDots.length; i += CHUNK) {
  const slice = landDots.slice(i, i + CHUNK);
  lines.push(`  ${slice.map((n) => (Number.isInteger(n) ? String(n) : n.toFixed(2))).join(", ")},`);
}

const footer = `];
`;

writeFileSync(OUT, header + lines.join("\n") + footer);

console.log(
  `Wrote ${OUT} (${width}×${height}, ${landDots.length / 2} land dots, projection ${projection?.name ?? "mercator"})`,
);

const cities = [
  ["London", 51.5, -0.1],
  ["NYC", 40.7, -74],
  ["Tokyo", 35.7, 139.7],
  ["Auckland", -36.8, 174.8],
  ["Ushuaia", -54.8, -68.3],
];
for (const [name, lat, lng] of cities) {
  const pin = map.getPin({ lat, lng });
  if (!pin) console.warn(`Warning: ${name} did not project`);
}
